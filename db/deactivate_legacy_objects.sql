-- Чистка справочника объектов. Задание от 08.09.2026, шаг 1, задача 1.2.
--
-- Деактивация, НЕ удаление. Сводки деактивированных объектов остаются
-- видимыми: ни all_reports, ни my_reports, ни оба экспорта не фильтруют
-- по objects.is_active. Объект лишь исчезает из списков выбора —
-- /api/objects, /api/users/<id>/objects и /api/projects/<id>/objects.
--
-- Что деактивируем:
--   1  — «ЖК «Окла» (уч.24 к.5.3.1, уч.18 к.2.2.1)», зонтичный
--        предшественник объектов 11 и 12; 30 сводок до 21.06.2026 остаются
--   4  — старая копия дома 2.2.1 (живая версия — 12)
--   8  — старая копия дома 5.3.1 (живая версия — 11)
--   10 — старая копия школы (живая версия — 13)
--   3, 6, 7 — пустые, сводок нет
--
-- НЕ трогаем: 2 (IQ Гатчина), 11, 12, 13, 14 (ДОУ) — живые.
--
-- Условие is_active=1 делает скрипт идемпотентным: повторный запуск
-- ничего не изменит и вернёт 0 строк.

BEGIN;

UPDATE objects
   SET is_active = 0
 WHERE id IN (1, 3, 4, 6, 7, 8, 10)
   AND is_active = 1;

COMMIT;

-- Контроль: перечисленные должны стать 0, живые остаться 1
SELECT id,
       name,
       is_active,
       (SELECT COUNT(*) FROM daily_reports dr WHERE dr.object_id = o.id) AS сводок
  FROM objects o
 ORDER BY id;
